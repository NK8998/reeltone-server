CREATE TABLE members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id text NOT NULL UNIQUE,
    username text NOT NULL,
    email text NOT NULL,
    pfp_url text,
    joined_at timestamptz DEFAULT now()
);

CREATE TABLE reviews (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id text NOT NULL,
    username text NOT NULL,
    pfp_url text,
    film_id bigint NOT NULL,
    film_title text NOT NULL,
    film_poster text,
    rating double precision CHECK (rating BETWEEN 0 AND 10),
    review_text text,
    is_parent boolean DEFAULT false,
    parent_id bigint,
    like_count integer DEFAULT 0,
    created_at timestamptz DEFAULT now(),
    updated_at timestamptz DEFAULT now()
);
CREATE INDEX reviews_film ON reviews (film_id);
CREATE INDEX reviews_user ON reviews (user_id);

CREATE TABLE review_likes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id text NOT NULL,
    review_id bigint NOT NULL,
    created_at timestamptz DEFAULT now(),
    UNIQUE (user_id, review_id)
);

CREATE TABLE film_likes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id text NOT NULL,
    film_id bigint NOT NULL,
    created_at timestamptz DEFAULT now(),
    UNIQUE (user_id, film_id)
);

CREATE TABLE watchlist (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id text NOT NULL,
    film_id bigint NOT NULL,
    film_title text,
    film_poster text,
    added_at timestamptz DEFAULT now(),
    UNIQUE (user_id, film_id)
);

CREATE TABLE watched (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id text NOT NULL,
    film_id bigint NOT NULL,
    film_title text,
    film_poster text,
    watched_at timestamptz DEFAULT now(),
    UNIQUE (user_id, film_id)
);

CREATE TABLE followers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    follower_id text NOT NULL,
    followed_id text NOT NULL,
    followed_at timestamptz DEFAULT now(),
    UNIQUE (follower_id, followed_id)
);
CREATE INDEX followers_followed ON followers (followed_id);

CREATE TABLE reviews_sessions (
    token_hash text PRIMARY KEY,
    profile text NOT NULL,
    expires_at bigint NOT NULL
);
CREATE INDEX reviews_sessions_expiry ON reviews_sessions (expires_at);
