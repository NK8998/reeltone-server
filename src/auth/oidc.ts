import { Inject, Injectable } from '@nestjs/common';
import { Provider, errors, type Adapter, type AdapterPayload } from 'oidc-provider';
import { config } from './config.js';
import { Database } from './db.js';

class PostgresAdapter implements Adapter {
  constructor(private readonly db: Database, private readonly model: string) {}

  async upsert(id: string, payload: AdapterPayload, expiresIn?: number) {
    await this.db.query(
      `INSERT INTO oidc_artifacts (model, id, payload, expires_at, grant_id, interaction_uid, user_code)
       VALUES ($1, $2, $3, COALESCE(now() + $4::integer * interval '1 second', 'infinity'), $5, $6, $7)
       ON CONFLICT (model, id) DO UPDATE SET payload = EXCLUDED.payload, expires_at = EXCLUDED.expires_at,
       grant_id = EXCLUDED.grant_id, interaction_uid = EXCLUDED.interaction_uid, user_code = EXCLUDED.user_code`,
      [this.model, id, payload, expiresIn, payload.grantId, payload.uid, payload.userCode],
    );
  }

  find(id: string) { return this.lookup('id', id); }
  findByUid(uid: string) { return this.lookup('interaction_uid', uid); }
  findByUserCode(code: string) { return this.lookup('user_code', code); }

  private async lookup(column: 'id' | 'interaction_uid' | 'user_code', value: string) {
    const { rows: [row] } = await this.db.query<{ payload: AdapterPayload; consumed_at: Date | null }>(
      `SELECT payload, consumed_at FROM oidc_artifacts WHERE model = $1 AND ${column} = $2 AND expires_at > now()`,
      [this.model, value],
    );
    if (!row) return;
    return row.consumed_at ? { ...row.payload, consumed: Math.floor(row.consumed_at.getTime() / 1000) } : row.payload;
  }

  async consume(id: string) {
    const result = await this.db.query(
      'UPDATE oidc_artifacts SET consumed_at = now() WHERE model = $1 AND id = $2 AND consumed_at IS NULL AND expires_at > now()',
      [this.model, id],
    );
    if (!result.rowCount) throw new errors.InvalidGrant('credential is expired or already used');
  }

  async destroy(id: string) {
    await this.db.query('DELETE FROM oidc_artifacts WHERE model = $1 AND id = $2', [this.model, id]);
  }

  async revokeByGrantId(id: string) {
    await this.db.query('DELETE FROM oidc_artifacts WHERE grant_id = $1', [id]);
  }
}

@Injectable()
export class OidcService {
  readonly provider: Provider;

  constructor(@Inject(Database) db: Database) {
    const cookie = { httpOnly: true, secure: config.secure, sameSite: 'lax' as const };
    this.provider = new Provider(config.issuer, {
      adapter: (model) => new PostgresAdapter(db, model),
      clients: config.clients,
      jwks: config.jwks,
      cookies: { keys: [config.secret], short: cookie, long: cookie },
      pkce: { required: () => true },
      responseTypes: ['code'],
      features: {
        devInteractions: { enabled: false },
        rpInitiatedLogout: { enabled: true },
      },
      interactions: { url: (_ctx, interaction) => `/interaction/${interaction.uid}` },
      scopes: ['openid', 'profile', 'email'],
      claims: {
        openid: ['sub'],
        profile: ['preferred_username', 'given_name', 'family_name', 'picture'],
        email: ['email', 'email_verified'],
      },
      async findAccount(_ctx, id) {
        // OIDC account IDs are generated by PostgreSQL.
        if (!/^[a-f0-9-]{36}$/i.test(id)) return;
        const { rows: [account] } = await db.query<{
          username: string; first_name: string | null; last_name: string | null;
          profile_picture_url: string | null; email: string | null; verified_at: Date | null;
        }>(
          `SELECT a.username, a.first_name, a.last_name, a.profile_picture_url, e.email, e.verified_at
           FROM accounts a LEFT JOIN account_emails e ON a.id = e.account_id AND e.is_primary
           WHERE a.id = $1 AND a.status = 'active'`,
          [id],
        );
        if (!account) return;
        return {
          accountId: id,
          async claims() {
            return {
              sub: id, preferred_username: account.username,
              given_name: account.first_name ?? undefined, family_name: account.last_name ?? undefined,
              picture: account.profile_picture_url ?? undefined, email: account.email ?? undefined,
              email_verified: account.email ? Boolean(account.verified_at) : undefined,
            };
          },
        };
      },
    });
    (this.provider as unknown as { proxy: boolean }).proxy = config.trustProxy;
  }
}
